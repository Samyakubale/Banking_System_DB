-- FUNCTIONS


-- STRING FUNCTIONS
SELECT CUSTOMERID, CONCAT(FIRSTNAME," ",LASTNAME) AS FULL_NAME
FROM CUSTOMERS;

-- UPPER 
SELECT CUSTOMERID, UPPER(CONCAT(FIRSTNAME," ",LASTNAME)) AS FULL_NAME
FROM CUSTOMERS;

-- LOWER 
SELECT CUSTOMERID, LOWER(CONCAT(FIRSTNAME," ",LASTNAME)) AS FULL_NAME
FROM CUSTOMERS;

-- LENGTH
SELECT FIRSTNAME, LENGTH(FIRSTNAME) AS NAME_LENGTH
FROM CUSTOMERS
HAVING NAME_LENGTH <= 5
ORDER BY NAME_LENGTH DESC LIMIT 1 OFFSET 1; -- OFFSET IS USED TO SKIP THE VALUE

-- CHAR_LENGTH
SELECT FIRSTNAME, CHAR_LENGTH(FIRSTNAME) AS CHARACTER_LENGTH
FROM CUSTOMERS;

-- LEFT
SELECT FIRSTNAME,LEFT(FIRSTNAME,3)
FROM CUSTOMERS;

-- RIGHT
SELECT PHONE,RIGHT(PHONE,4) AS LAST_4_DIGITS
FROM CUSTOMERS;
SELECT CUSTOMERID,CONCAT("XXXX",RIGHT(PHONE,4)) MASKED_PHONENO
FROM CUSTOMERS;

-- SUBSTRING
SELECT EMAIL,SUBSTRING(EMAIL,1,5) AS EMAIL_PART
FROM CUSTOMERS;

-- SUBSTRING_INDEX
SELECT EMAIL,SUBSTRING_INDEX(EMAIL,"@",-1) AS EMAIL_PART 				-- 1 BEFORE SPECIFIC CHAR, -1 FOR AFTER SPECIFIC CHAR
FROM CUSTOMERS;

-- TRIM
SELECT TRIM("SAMYAK UBALE          ") AS NAME;							-- REMOVES USELESS SPACES

-- REPLACE
SELECT EMAIL,REPLACE(EMAIL,'gmail.com','email.com') AS EMAILS
FROM CUSTOMERS;

-- LOCATE
SELECT EMAIL, LOCATE("@",EMAIL) AS POSITION				-- LOCATE POSITION
FROM CUSTOMERS;


-- MATH FUNCTION


-- ROUND
SELECT ACCOUNTID,BALANCE,ROUND(BALANCE,0)AS ROUNDED_BALANCE				-- ROUNDS OF THE DECIMAL VALUE
FROM ACCOUNTS;

-- CEIL/CEILING
SELECT BALANCE,CEIL(BALANCE) AS ROUNDUP_BALANCE
FROM ACCOUNTS;															 -- ROUNDS UP THE VALUE

-- FLOOR
SELECT BALANCE,FLOOR(BALANCE) AS ROUNDUP_BALANCE
FROM ACCOUNTS;															-- ROUNDS DOWN THE VALUE

-- ABS
SELECT ABS(-6548) AS ABSOLUTE_VALUE;									-- RETURNS ABSOULTE VALUE

-- MOD
SELECT ACCOUNTID,MOD(ACCOUNTID,2) AS REMINDER
FROM ACCOUNTS;															-- RETURNS REMAINING VALUE

-- CASE THEN END IS JUST LIKE IF - ELSE STATEMENT
SELECT ACCOUNTID,MOD(ACCOUNTID,2) AS REMINDER,CASE
WHEN MOD(ACCOUNTID,2)=0 THEN "EVEN"
ELSE "ODD"
END AS ID_TYPE
FROM ACCOUNTS;

-- POWER
SELECT POWER(5,5)
AS RESULT;													-- WORKS LIKE INDICES

-- SQRT
SELECT BALANCE,SQRT(BALANCE) AS SQRT
FROM ACCOUNTS;												-- RETURNS SQUAREROOT

-- GREATEST 
SELECT ACCOUNTID, BALANCE,GREATEST(BALANCE,25000) AS MINIMUM_BALANCE 
FROM ACCOUNTS;													-- COMPARES VALUES

-- LEAST
SELECT ACCOUNTID,BALANCE,LEAST(BALANCE,50000) AS MAX_LIMIT
FROM ACCOUNTS;													-- COMPARES VALUES

-- CALCULATE ANNUAL INTEREST
SELECT LOANID,LOANAMOUNT,INTERESTRATE, ROUND(LOANAMOUNT * INTERESTRATE /100,2) AS ANNUAL_INTEREST
FROM LOANS;

-- LOAN AMOUNT + INTEREST
SELECT LOANID,LOANAMOUNT,INTERESTRATE,
ROUND(LOANAMOUNT+(LOANAMOUNT * INTERESTRATE / 100),2) AS PRINCIPAL_PLUS_ONEYEAR_INTEREST
FROM LOANS;

-- BALANCE CATEGORY
SELECT ACCOUNTID,BALANCE,
CASE
WHEN BALANCE IS NULL THEN "UNKNOWN"
WHEN BALANCE < 10000 THEN"LOW"
WHEN BALANCE < 50000 THEN "MEDIUM"
ELSE "HIGH"
END AS BALANCE_CATEGORY
FROM ACCOUNTS;


