-- WINDOWS FUNCTIONS


-- RANK & OVER
SELECT LOANID,LOANAMOUNT,RANK() OVER(ORDER BY LOANAMOUNT DESC) AS LOAN_RANK
FROM LOANS;

SELECT * FROM TRANSACTIONS;
SELECT TRANSACTIONID,AMOUNT,RANK() OVER(ORDER BY AMOUNT DESC) AS TRANSACTION_RANK,
DENSE_RANK() OVER(ORDER BY AMOUNT DESC) AS TRANSACTION_DENSE_RANK								-- DENSE RANK (NEVER SKIPS RANK VALUES)
FROM TRANSACTIONS;

SELECT TRANSACTIONID,TRANSACTIONTYPE,AMOUNT,
DENSE_RANK() OVER(PARTITION BY TRANSACTIONTYPE ORDER BY AMOUNT DESC) AS TRANSACTION_RANK		-- PARTITION BY
FROM TRANSACTIONS;

-- ROW NUMBER
